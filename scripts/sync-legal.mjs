// Copies the legal documents in legal/*.md into the app (src/lib/legalDocs.ts), so they can be read
// inside Peekaboo even without internet. Run it after changing any file in legal/:
//
//   node scripts/sync-legal.mjs
//
// Operator-only parts (the dare review checklist and implementation notes) are left out of the app.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (name) => readFileSync(join(root, 'legal', name), 'utf8').replace(/\r\n/g, '\n').trim();

// Everything from `heading` onwards is for the operator, not users.
const cutFrom = (text, heading) => {
  const at = text.indexOf(heading);
  return at === -1 ? text : text.slice(0, at).trim();
};

const docs = {
  terms: read('TERMS_OF_SERVICE.md'),
  privacy: read('PRIVACY_POLICY.md'),
  guidelines: read('COMMUNITY_GUIDELINES.md'),
  'dare-rules': cutFrom(read('DARE_SAFETY_RULES.md'), '## The "I understand" screen'),
};

const out = `// Generated by scripts/sync-legal.mjs from the files in legal/ – don't edit by hand.
// Run \`node scripts/sync-legal.mjs\` after changing a legal document.

export const LEGAL_DOCS = ${JSON.stringify(docs, null, 2)} as const;
`;
writeFileSync(join(root, 'src/lib/legalDocs.ts'), out);
console.log(`Wrote src/lib/legalDocs.ts (${Object.keys(docs).join(', ')})`);
